import type { DrawingSymbol, DrawPoint } from "@/types/drawing";

const stroke = (...coordinates: number[]): DrawPoint[] =>
  coordinates.reduce<DrawPoint[]>((points, value, index) => {
    if (index % 2 === 0) points.push({ x: value, y: coordinates[index + 1]! });
    return points;
  }, []);
function oval(cx: number, cy: number, rx: number, ry = rx): DrawPoint[] {
  return Array.from({ length: 49 }, (_, i) => ({
    x: cx + rx * Math.cos((i / 48) * Math.PI * 2),
    y: cy + ry * Math.sin((i / 48) * Math.PI * 2),
  }));
}
const box = (x: number, y: number, w: number, h: number) =>
  stroke(x, y, x + w, y, x + w, y + h, x, y + h, x, y);
const symbol = (
  id: string,
  label: string,
  category: string,
  ...strokes: DrawPoint[][]
): DrawingSymbol => ({ id, label, category, strokes });

